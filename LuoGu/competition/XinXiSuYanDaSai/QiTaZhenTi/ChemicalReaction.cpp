#include <iostream>
using namespace std;

int main() {
    int a, b;
    cin >> a >> b;
    
    // 化学试剂混合问题
    // 甲和乙的实验结果：0表示发生危险反应，1表示安全
    // 需要判断被污染的试剂编号
    
    // 分析逻辑：
    // 试剂1,2,3,4中有一种被污染
    // 甲的实验：混合了1号和2号试剂
    // 乙的实验：混合了1号和3号试剂
    
    // 根据实验结果推断：
    if (a == 1 && b == 1) {
        // 甲安全，乙安全 → 1号试剂安全，2号和3号都安全 → 4号被污染
        cout << 4 << endl;
    }
    else if (a == 1 && b == 0) {
        // 甲安全，乙危险 → 1号和2号安全，3号被污染
        cout << 3 << endl;
    }
    else if (a == 0 && b == 1) {
        // 甲危险，乙安全 → 1号和3号安全，2号被污染
        cout << 2 << endl;
    }
    else { // a == 0 && b == 0
        // 甲危险，乙危险 → 1号被污染（两个实验都有1号）
        cout << 1 << endl;
    }
    
    return 0;
} 
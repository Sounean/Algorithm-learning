#include "iostream"

using namespace std;

int a[60];
int main(){
    // 这题有点难思考如何去遍历？ 这题感觉递归才方便吧
    // 不，用逆推得思路也可以，即到达最后放满之前，差最后一步时，有多少种可能性，
    // 有三种大可能性：1.最左侧差1格时，左侧的所有摆放方式；2.最左侧差2格时，左侧的所有摆放方式；3.最右侧差3格时，左侧所有的摆放方式；
    int n;
    cin >> n;
    // 初始值设置：
    // a[0] = 1 (空的情况，1种方法，虽然不会用到，但递推时需要)
    // a[1] = 1 (1个1x1骨牌)
    // a[2] = 2 (1个1x2骨牌 或 2个1x1骨牌)
    // a[3] = 4 (题目给出，也可以用递推验证：a[3] = a[2] + a[1] + a[0] = 2 + 1 + 1 = 4)
    a[0] = 1;  // 空的情况，递推时用到
    a[1] = 1;
    a[2] = 2;  // 修正：应该是2，不是3
    a[3] = 4;
    if (n<4){
        cout << a[n];
    } else{
        for (int i = 4; i <=n; ++i) {
            a[i] = a[i-1]+a[i-2]+a[i-3];
        }
        cout << a[n];
    }



    return 0;
}
